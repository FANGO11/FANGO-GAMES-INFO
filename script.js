let currentLanguage = getInitialLanguage();
let currentPage = "introduction";

const content = document.getElementById("content");
const languageLabel = document.getElementById("languageLabel");
const languageButton = document.getElementById("languageButton");
const languageMenu = document.getElementById("languageMenu");
const menuToggle = document.getElementById("menuToggle");
const mainNav = document.getElementById("mainNav");

function getInitialLanguage() {
    const saved = localStorage.getItem("ttw-language");
    if (saved && translations[saved]) return saved;

    const browser = (navigator.language || "en").toLowerCase();
    if (browser.startsWith("uk")) return "uk";
    if (browser.startsWith("ro")) return "ro";
    return "en";
}

function t(path) {
    return path.split(".").reduce((obj, key) => obj?.[key], translations[currentLanguage]);
}

function setLanguage(language) {
    if (!translations[language]) return;

    currentLanguage = language;
    localStorage.setItem("ttw-language", language);
    document.documentElement.lang = language;
    languageLabel.textContent = t("languageName");

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const value = t(element.dataset.i18n);
        if (value) element.textContent = value;
    });

    render(currentPage);
    closeLanguage();
}

function setActivePage(page) {
    document.querySelectorAll("[data-page]").forEach((element) => {
        element.classList.toggle("active", element.dataset.page === page);
    });

    document.querySelectorAll(".nav-group").forEach((group) => {
        const pages = [...group.querySelectorAll("[data-page]")].map(el => el.dataset.page);
        const isActive = pages.includes(page);
        group.classList.toggle("active-group", isActive);
    });
}

function openGroup(groupElement) {
    document.querySelectorAll(".nav-group").forEach(group => {
        if (group !== groupElement) {
            group.classList.remove("open");
            group.querySelector(".nav-parent")?.setAttribute("aria-expanded", "false");
        }
    });

    groupElement.classList.toggle("open");
    groupElement.querySelector(".nav-parent")?.setAttribute(
        "aria-expanded",
        String(groupElement.classList.contains("open"))
    );
}

function closeMenus() {
    document.querySelectorAll(".nav-group").forEach(group => {
        group.classList.remove("open");
        group.querySelector(".nav-parent")?.setAttribute("aria-expanded", "false");
    });
    closeLanguage();
}

function closeLanguage() {
    document.querySelector(".language")?.classList.remove("open");
    languageButton?.setAttribute("aria-expanded", "false");
}

function render(page) {
    currentPage = page;
    setActivePage(page);

    const p = translations[currentLanguage].pages;

    const templates = {
        introduction: `
            <section class="page hero">
                <div class="hero-inner">
                    <span class="eyebrow">${p.introduction.eyebrow}</span>
                    <h1>${p.introduction.title}</h1>
                    <p class="lead">${p.introduction.lead}</p>
                    <div class="actions">
                        <button class="button primary" data-page="ttw-about">${p.introduction.primary}</button>
                        <button class="button" data-page="ul-about">${p.introduction.secondary}</button>
                    </div>
                </div>
            </section>
            <section class="page">
                <div class="section-heading">
                    <h2>${p.introduction.heading}</h2>
                    <p>${p.introduction.text}</p>
                </div>
                <div class="cards">
                    <article class="card"><h3>${p.ttw.aboutTitle}</h3><p>${p.ttw.aboutText}</p></article>
                    <article class="card"><h3>${p.ul.aboutTitle}</h3><p>${p.ul.aboutText}</p></article>
                    <article class="card"><h3>${p.ttw.templateTitle}</h3><p>${p.ttw.templateText}</p></article>
                </div>
            </section>
        `,

        "ttw-about": projectAbout("ttw"),
        "ul-about": projectAbout("ul"),
        "ttw-updates": projectUpdates("ttw"),
        "ul-updates": projectUpdates("ul"),
        "ttw-levels": projectLevels("ttw"),
        "ul-levels": projectLevels("ul"),

        template: `
            <section class="page">
                <div class="section-heading">
                    <span class="eyebrow">${p.introduction.eyebrow}</span>
                    <h2>${p.ttw.templateTitle}</h2>
                    <p>${p.ttw.templateText}</p>
                </div>
                <div class="notice">${p.common.comingSoon}</div>
            </section>
        `,

        eula: `
            <section class="page prose">
                <span class="eyebrow">EULA</span>
                <h2>${p.common.eulaTitle}</h2>
                <p>${p.common.eulaText}</p>
                <div class="notice">
                    ${p.common.status}: ${p.common.comingSoon}
                </div>
            </section>
        `
    };

    content.innerHTML = templates[page] || templates.introduction;
    content.focus({ preventScroll: true });

    content.querySelectorAll("[data-page]").forEach(button => {
        button.addEventListener("click", () => {
            navigate(button.dataset.page);
        });
    });

    document.title = page === "introduction"
        ? "Through The Wind"
        : `${page.replace("-", " ")} — Through The Wind`;
}

function projectAbout(project) {
    const data = translations[currentLanguage].pages[project];
    return `
        <section class="page">
            <div class="section-heading">
                <span class="eyebrow">${data.aboutTitle}</span>
                <h2>${data.aboutTitle}</h2>
                <p>${data.aboutText}</p>
            </div>
            <div class="stats">
                <div class="stat"><strong>TTW</strong><span>${translations[currentLanguage].pages.common.currentVersion}</span></div>
                <div class="stat"><strong>∞</strong><span>${translations[currentLanguage].pages.common.latest}</span></div>
                <div class="stat"><strong>●</strong><span>${translations[currentLanguage].pages.common.available}</span></div>
            </div>
            <div class="card"><h3>${translations[currentLanguage].pages.ttw.aboutTitle}</h3><p>${data.aboutText}</p></div>
        </section>
    `;
}

function projectUpdates(project) {
    const data = translations[currentLanguage].pages[project];
    return `
        <section class="page">
            <div class="section-heading">
                <span class="eyebrow">${data.aboutTitle}</span>
                <h2>${data.updateTitle}</h2>
                <p>${data.updateText}</p>
            </div>
            <div class="notice">${translations[currentLanguage].pages.common.noUpdates}</div>
        </section>
    `;
}

function projectLevels(project) {
    const data = translations[currentLanguage].pages[project];
    const common = translations[currentLanguage].pages.common;
    return `
        <section class="page">
            <div class="section-heading">
                <span class="eyebrow">${data.aboutTitle}</span>
                <h2>${data.levelsTitle}</h2>
                <p>${data.levelsText}</p>
            </div>
            <div class="level-list">
                <div class="level"><strong>Level 01</strong><span>${common.comingSoon}</span></div>
                <div class="level"><strong>Level 02</strong><span>${common.comingSoon}</span></div>
                <div class="level"><strong>Level 03</strong><span>${common.comingSoon}</span></div>
            </div>
            <div class="notice">${common.levelsPlaceholder}</div>
        </section>
    `;
}

function navigate(page) {
    if (!page) return;

    currentPage = page;
    history.pushState({ page }, "", `#${page}`);
    render(page);
    closeMenus();
    window.scrollTo({ top: 0, behavior: "smooth" });

    if (mainNav.classList.contains("open")) {
        mainNav.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");
    }
}

document.addEventListener("click", (event) => {
    const pageButton = event.target.closest("[data-page]");
    const groupParent = event.target.closest(".nav-parent");

    if (pageButton && !groupParent) {
        navigate(pageButton.dataset.page);
        return;
    }

    if (groupParent) {
        event.preventDefault();
        openGroup(groupParent.closest(".nav-group"));
    }

    if (!event.target.closest(".language")) closeLanguage();
    if (!event.target.closest(".nav-group")) {
        document.querySelectorAll(".nav-group").forEach(group => group.classList.remove("open"));
    }
});

document.querySelectorAll("[data-language]").forEach(button => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
});

languageButton.addEventListener("click", () => {
    const language = languageButton.closest(".language");
    const isOpen = language.classList.toggle("open");
    languageButton.setAttribute("aria-expanded", String(isOpen));
});

menuToggle.addEventListener("click", () => {
    const open = mainNav.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(open));
});

window.addEventListener("popstate", () => {
    const page = location.hash.replace("#", "") || "introduction";
    render(page);
});

document.getElementById("year").textContent = new Date().getFullYear();

const initialPage = location.hash.replace("#", "") || "introduction";
render(initialPage);
setLanguage(currentLanguage);
